const dict: Record<Lang, Strings> = { en, hi, mr };
export const photoText = (lang: Lang, key: PhotoKey, vars?: Record<string, string | number>) => {
  let s = dict[lang][key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
};
